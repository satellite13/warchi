#!/usr/bin/env node
/**
 * Sync self-hosted Manrope + JetBrains Mono woff2 into public/fonts
 * and regenerate public/landing-fonts.css for CSP-safe landing.html.
 */
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = join(root, 'public', 'fonts')
const cssPath = join(root, 'public', 'landing-fonts.css')

const CYRILLIC_RANGE = 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116'
const LATIN_RANGE =
  'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD'

const fonts = [
  {
    family: 'Manrope',
    pkg: '@fontsource/manrope',
    prefix: 'manrope',
    weights: [400, 500, 600, 700, 800],
  },
  {
    family: 'JetBrains Mono',
    pkg: '@fontsource/jetbrains-mono',
    prefix: 'jetbrains-mono',
    weights: [400, 500, 700],
  },
]

mkdirSync(outDir, { recursive: true })

const faces = []
for (const font of fonts) {
  const filesDir = join(dirname(require.resolve(`${font.pkg}/package.json`)), 'files')
  for (const weight of font.weights) {
    for (const subset of ['cyrillic', 'latin']) {
      const name = `${font.prefix}-${subset}-${weight}-normal.woff2`
      copyFileSync(join(filesDir, name), join(outDir, name))
      faces.push(`/* ${name} */
@font-face {
  font-family: '${font.family}';
  font-style: normal;
  font-display: swap;
  font-weight: ${weight};
  src: url('/fonts/${name}') format('woff2');
  unicode-range: ${subset === 'cyrillic' ? CYRILLIC_RANGE : LATIN_RANGE};
}`)
    }
  }
}

writeFileSync(
  cssPath,
  `/* Generated by scripts/sync-landing-fonts.mjs — do not edit by hand. */\n\n${faces.join('\n\n')}\n`
)
console.log(`Synced ${faces.length} font faces → public/fonts + landing-fonts.css`)
